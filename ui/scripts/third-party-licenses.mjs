// Writes THIRD-PARTY-LICENSES.md into the repository: the Rust crates that end
// up in the shipped program (runtime dependencies only – no build scripts, no
// test-only crates), each with its license and the license texts from its
// source folder, plus the bundled libopus. Identical texts appear once.
// Node built-ins only; needs `cargo` (reads Cargo.lock, changes nothing).
//
//   node ui/scripts/third-party-licenses.mjs --target=wasm32-unknown-unknown   (this repository: the browser version)
//   node klangwelt/ui/scripts/third-party-licenses.mjs --root=.                (klangwelt-desktop: all desktop platforms)
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const arg = (name) => process.argv.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3);
/** Repository whose Cargo.lock is listed and that receives THIRD-PARTY-LICENSES.md. */
const root = resolve(arg("root") ?? here);
/** Only the dependencies of this target (e.g. wasm32-unknown-unknown); default: all platforms. */
const target = arg("target");
const meta = JSON.parse(
  execFileSync(
    "cargo",
    ["metadata", "--format-version", "1", "--locked", "--manifest-path", join(root, "Cargo.toml"), ...(target ? ["--filter-platform", target] : [])],
    { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 },
  ),
);
const own = new Set(meta.workspace_members);

// What ships: everything reachable from our crates over normal dependencies.
// Build-dependencies only run while compiling, dev-dependencies only in tests,
// and proc-macro crates (e.g. serde_derive) only inside the compiler.
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const procMacro = new Set(meta.packages.filter((p) => p.targets.some((t) => t.kind.includes("proc-macro"))).map((p) => p.id));
const shipped = new Set();
const todo = [...own];
while (todo.length) {
  const id = todo.pop();
  if (shipped.has(id)) continue;
  shipped.add(id);
  for (const d of nodes.get(id)?.deps ?? []) {
    if (d.dep_kinds.some((k) => k.kind == null) && !procMacro.has(d.pkg)) todo.push(d.pkg);
  }
}
const LICENSE_FILE = /^(licen[sc]e|copying|notice|unlicense|copyright)([-._].*)?$/i;

/** License texts in a package folder (LICENSE, LICENSE-MIT, COPYING, NOTICE …). */
function licenseTexts(dir) {
  let names = [];
  try {
    names = readdirSync(dir).filter((n) => LICENSE_FILE.test(n)).sort();
  } catch {
    return [];
  }
  return names.map((n) => ({ file: n, text: readFileSync(join(dir, n), "utf8").replace(/\r\n/g, "\n").trim() }));
}

const packages = meta.packages
  // not ours (workspace members, local path dependencies like the core in the submodule), and shipped
  .filter((p) => !own.has(p.id) && p.source != null && shipped.has(p.id))
  .map((p) => ({
    name: p.name,
    version: p.version,
    license: p.license ?? (p.license_file ? `see ${p.license_file}` : "not specified"),
    repo: p.repository ?? "",
    texts: licenseTexts(dirname(p.manifest_path)),
  }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true }));

// Bundled, but not a Cargo package of its own: libopus in crates/klang-opus.
packages.push({
  name: "libopus (in crates/klang-opus)",
  version: "",
  license: "BSD-3-Clause",
  repo: "https://opus-codec.org",
  texts: licenseTexts(join(here, "crates", "klang-opus", "opus")),
});

// Merge identical texts: text → number, package → numbers.
const textIds = new Map();
for (const p of packages) {
  p.refs = p.texts.map((t) => {
    if (!textIds.has(t.text)) textIds.set(t.text, { id: textIds.size + 1, file: t.file, users: [] });
    const entry = textIds.get(t.text);
    entry.users.push(p.version ? `${p.name} ${p.version}` : p.name);
    return entry.id;
  });
}

const out = [];
out.push("# Third-party licenses", "");
out.push(
  "Klangwelt itself is licensed under the MIT License (see `LICENSE`). This file lists the",
  "libraries by others that are built into the program, together with their licenses.",
  target
    ? `Generated by \`ui/scripts/third-party-licenses.mjs\` from \`Cargo.lock\` for \`${target}\`: the crates that end up in the program (no build tools, proc macros or test-only crates).`
    : "Generated by `ui/scripts/third-party-licenses.mjs` from `Cargo.lock` for all desktop platforms (so it also lists crates only needed on Windows, macOS or Linux): the crates that end up in the program (no build tools, proc macros or test-only crates).",
  "The user interface has no runtime dependencies.",
  "",
);
out.push(`## Packages (${packages.length})`, "");
out.push("| Package | Version | License | License text |", "|---|---|---|---|");
for (const p of packages) {
  const name = p.repo ? `[${p.name}](${p.repo})` : p.name;
  const refs = p.refs.length ? p.refs.map((n) => `[${n}](#text-${n})`).join(", ") : "–";
  out.push(`| ${name} | ${p.version} | ${p.license.replace(/\|/g, "\\|")} | ${refs} |`);
}
out.push("", "## License texts", "");
for (const [text, { id, file, users }] of textIds) {
  out.push(`### <a id="text-${id}"></a>Text ${id} (${file})`, "");
  out.push(`Applies to: ${users.join(", ")}`, "");
  out.push("```text", text.replace(/```/g, "ʼʼʼ"), "```", "");
}
const missing = packages.filter((p) => !p.texts.length).map((p) => `${p.name} ${p.version}`);
if (missing.length) {
  out.push("## Without a license file in the package", "");
  out.push("These packages name their license only in `Cargo.toml` (see the table); the standard text of that license applies.", "");
  out.push(missing.join(", "), "");
}

writeFileSync(join(root, "THIRD-PARTY-LICENSES.md"), out.join("\n"));
console.log(`THIRD-PARTY-LICENSES.md: ${packages.length} packages, ${textIds.size} distinct license texts, ${missing.length} without a license file`);
